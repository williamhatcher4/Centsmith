def regenerate() -> Path:
    """Write every corpus fixture file and the manifest.json contract."""
    CORPUS_DIR.mkdir(parents=True, exist_ok=True)
    entries = []
    for entry in CORPUS:
        (CORPUS_DIR / entry["filename"]).write_bytes(entry["build"]())
        manifest_entry = {k: v for k, v in entry.items() if k != "build"}
        entries.append(manifest_entry)
    MANIFEST_PATH.write_text(
        json.dumps({"_README": MANIFEST_README, "fixtures": entries}, indent=2) + "\n",
        encoding="utf-8",
    )
    return MANIFEST_PATH


if __name__ == "__main__":
    path = regenerate()
    print(f"Wrote {len(CORPUS)} corpus fixtures + manifest at {path}")
