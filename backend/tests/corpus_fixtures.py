"""Statement fixture corpus builder (plan item P5.5).

Every parser bug that reached users came from a real file *shape* no synthetic
fixture anticipated (AmEx formal CSV sign convention; preamble + Summary blocks;
``;``-in-description delimiter break). This module is the single source of truth
for a manifest-driven corpus: it writes one fixture file per supported bank/format
shape into ``fixtures/corpus/`` plus a ``manifest.json`` that
``test_statement_corpus.py`` checks field-by-field after parsing.

It is named without a ``test_`` prefix so pytest does not collect it.

Regenerate (from ``backend/`` with the venv active)::

    python -m tests.corpus_fixtures

SANITIZATION RULE (mandatory): every fixture is either builder-generated (these)
or field-by-field scrubbed (merchant names replaced, amounts altered, account
fragments removed). **Committing an unscrubbed real statement is forbidden** —
the same rule that keeps ``statements/`` gitignored. Each manifest entry records
its ``provenance``.

ONGOING RULE (the payoff): every user-reported import bug is fixed *with* a
sanitized fixture + manifest entry in the same change. The harness makes each new
fixture nearly free, and the corpus becomes the regression record of every bank
quirk ever encountered.

Each manifest ``expected`` block, by construction:
- ``format``             — ``StatementParseResult.statement_format``
- ``rows``               — number of rows the parser produced (``len(result.rows)``)
- ``skipped``            — ``result.skipped_errors``
- ``ignored_credits``    — rows the import filter drops for this source
                           (``_rows_for_source(result.rows, source, ignored_patterns)``)
- ``signed_total_cents`` — signed total over the *kept* (importable) rows
                           (+amount for credits, -amount for debits)
"""

